/* =========================================================
   LIGHTBOX DA GALERIA DOS PEQUENOS GRUPOS
========================================================= */

const lightbox =
    document.getElementById("pg-lightbox");


if (lightbox) {

    const imagemLightbox =
        document.getElementById("pg-lightbox-imagem");

    const contadorLightbox =
        document.getElementById("pg-lightbox-contador");

    const botaoFechar =
        document.getElementById("pg-lightbox-fechar");

    const botaoAnterior =
        document.getElementById("pg-lightbox-anterior");

    const botaoProximo =
        document.getElementById("pg-lightbox-proximo");


    let fotosGaleria = [];

    let fotoAtual = 0;


    /* =====================================================
       ABRIR LIGHTBOX
    ===================================================== */

    function abrirLightbox(indice) {

        fotoAtual = indice;

        atualizarLightbox();

        lightbox.classList.add("ativo");

        lightbox.setAttribute(
            "aria-hidden",
            "false"
        );

        document.body.style.overflow = "hidden";

    }


    /* =====================================================
       FECHAR LIGHTBOX
    ===================================================== */

    function fecharLightbox() {

        lightbox.classList.remove("ativo");

        lightbox.setAttribute(
            "aria-hidden",
            "true"
        );

        document.body.style.overflow = "";

    }


    /* =====================================================
       ATUALIZAR FOTO
    ===================================================== */

    function atualizarLightbox() {

        if (!fotosGaleria.length) {
            return;
        }


        imagemLightbox.src =
            fotosGaleria[fotoAtual].src;


        imagemLightbox.alt =
            fotosGaleria[fotoAtual].alt;


        contadorLightbox.textContent =
            `${fotoAtual + 1} / ${fotosGaleria.length}`;

    }


    /* =====================================================
       PRÓXIMA FOTO
    ===================================================== */

    function proximaFoto() {

        fotoAtual++;

        if (fotoAtual >= fotosGaleria.length) {

            fotoAtual = 0;

        }

        atualizarLightbox();

    }


    /* =====================================================
       FOTO ANTERIOR
    ===================================================== */

    function fotoAnterior() {

        fotoAtual--;

        if (fotoAtual < 0) {

            fotoAtual =
                fotosGaleria.length - 1;

        }

        atualizarLightbox();

    }


    /* =====================================================
       PEGAR FOTOS DA GALERIA
    ===================================================== */

    function prepararGaleria() {

        const imagens =
            document.querySelectorAll(
                "#pg-galeria-container img"
            );


        fotosGaleria =
            Array.from(imagens);


        imagens.forEach((imagem, indice) => {

            imagem.style.cursor = "pointer";


            imagem.addEventListener(
                "click",
                () => {

                    abrirLightbox(indice);

                }
            );

        });

    }


    /* =====================================================
       EVENTOS
    ===================================================== */

    botaoFechar.addEventListener(
        "click",
        fecharLightbox
    );


    botaoAnterior.addEventListener(
        "click",
        fotoAnterior
    );


    botaoProximo.addEventListener(
        "click",
        proximaFoto
    );


    /* =====================================================
       CLICAR FORA DA FOTO
    ===================================================== */

    lightbox.addEventListener(
        "click",
        (evento) => {

            if (
                evento.target === lightbox
            ) {

                fecharLightbox();

            }

        }
    );


    /* =====================================================
       TECLADO
    ===================================================== */

    document.addEventListener(
        "keydown",
        (evento) => {

            if (
                !lightbox.classList.contains("ativo")
            ) {
                return;
            }


            if (evento.key === "Escape") {

                fecharLightbox();

            }


            if (evento.key === "ArrowRight") {

                proximaFoto();

            }


            if (evento.key === "ArrowLeft") {

                fotoAnterior();

            }

        }
    );

    /* =========================================================
   SWIPE NO CELULAR
========================================================= */

    let toqueInicialX = 0;
    let toqueFinalX = 0;


    imagemLightbox.addEventListener(
        "touchstart",
        (evento) => {

            toqueInicialX =
                evento.changedTouches[0].screenX;

        }
    );


    imagemLightbox.addEventListener(
        "touchend",
        (evento) => {

            toqueFinalX =
                evento.changedTouches[0].screenX;


            const distancia =
                toqueFinalX - toqueInicialX;


            /* Ignora movimentos muito pequenos */

            if (Math.abs(distancia) < 50) {
                return;
            }


            /* Arrastou para a esquerda */

            if (distancia < 0) {

                proximaFoto();

            }


            /* Arrastou para a direita */

            else {

                fotoAnterior();

            }

        }
    );

    /* =====================================================
       INICIALIZAÇÃO
    ===================================================== */

    prepararGaleria();

}

