/* =========================================================
   LIGHTBOX - GALERIA DOS MINISTÉRIOS
========================================================= */

const galeriaImagens = document.querySelectorAll(".galeria-item");

const lightboxMinisterio =
    document.getElementById("lightbox");

const lightboxImagem =
    document.getElementById("lightboxImagem");

const lightboxFechar =
    document.getElementById("lightboxFechar");

const lightboxAnterior =
    document.getElementById("lightboxAnterior");

const lightboxProxima =
    document.getElementById("lightboxProxima");

let imagemAtual = 0;


if (
    galeriaImagens.length > 0 &&
    lightboxMinisterio &&
    lightboxImagem &&
    lightboxFechar &&
    lightboxAnterior &&
    lightboxProxima
) {

    function abrirLightbox(index) {

        imagemAtual = index;

        lightboxImagem.src =
            galeriaImagens[imagemAtual].src;

        lightboxImagem.alt =
            galeriaImagens[imagemAtual].alt;

        lightboxMinisterio.classList.add("ativo");

        document.body.style.overflow = "hidden";
    }


    function fecharLightbox() {

        lightboxMinisterio.classList.remove("ativo");

        document.body.style.overflow = "";
    }


    function proximaImagem() {

        imagemAtual++;

        if (
            imagemAtual >= galeriaImagens.length
        ) {
            imagemAtual = 0;
        }

        lightboxImagem.src =
            galeriaImagens[imagemAtual].src;

        lightboxImagem.alt =
            galeriaImagens[imagemAtual].alt;
    }


    function imagemAnterior() {

        imagemAtual--;

        if (imagemAtual < 0) {
            imagemAtual =
                galeriaImagens.length - 1;
        }

        lightboxImagem.src =
            galeriaImagens[imagemAtual].src;

        lightboxImagem.alt =
            galeriaImagens[imagemAtual].alt;
    }


    /* CLIQUE NAS FOTOS */

    galeriaImagens.forEach(
        (imagem, index) => {

            imagem.style.cursor = "pointer";

            imagem.addEventListener(
                "click",
                () => {
                    abrirLightbox(index);
                }
            );

        }
    );


    /* BOTÕES */

    lightboxFechar.addEventListener(
        "click",
        fecharLightbox
    );

    lightboxProxima.addEventListener(
        "click",
        proximaImagem
    );

    lightboxAnterior.addEventListener(
        "click",
        imagemAnterior
    );


    /* CLICAR NO FUNDO */

    lightboxMinisterio.addEventListener(
        "click",
        evento => {

            if (
                evento.target === lightboxMinisterio
            ) {
                fecharLightbox();
            }

        }
    );


    /* TECLADO */

    document.addEventListener(
        "keydown",
        evento => {

            if (
                !lightboxMinisterio.classList.contains("ativo")
            ) {
                return;
            }

            if (evento.key === "Escape") {
                fecharLightbox();
            }

            if (evento.key === "ArrowRight") {
                proximaImagem();
            }

            if (evento.key === "ArrowLeft") {
                imagemAnterior();
            }

        }
    );


    /* SWIPE NO CELULAR */

    let toqueInicialX = 0;
    let toqueFinalX = 0;


    lightboxImagem.addEventListener(
        "touchstart",
        evento => {

            toqueInicialX =
                evento.changedTouches[0].screenX;

        }
    );


    lightboxImagem.addEventListener(
        "touchend",
        evento => {

            toqueFinalX =
                evento.changedTouches[0].screenX;

            const distancia =
                toqueFinalX - toqueInicialX;

            if (Math.abs(distancia) < 50) {
                return;
            }

            if (distancia < 0) {
                proximaImagem();
            } else {
                imagemAnterior();
            }

        }
    );

}